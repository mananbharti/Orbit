// Exposes a narrow, fixed API to the page; no Node access and no arbitrary channels.
const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('orbit', {
  state: () => ipcRenderer.invoke('orbit:state'),
  onState: cb => { const f = (_e, s) => cb(s); ipcRenderer.on('orbit:state', f); return () => ipcRenderer.removeListener('orbit:state', f); },
  pair: () => ipcRenderer.invoke('orbit:pair'),
  cancelPair: () => ipcRenderer.invoke('orbit:cancel-pair'),
  revoke: id => ipcRenderer.invoke('orbit:revoke', id),
  retry: () => ipcRenderer.invoke('orbit:retry'),
  agentSave: (key, baseUrl, layaUrl, fastModel) => ipcRenderer.invoke('orbit:agent-save', key, baseUrl, layaUrl, fastModel),
  fastDetect: () => ipcRenderer.invoke('orbit:fast-detect'),
  agentClear: () => ipcRenderer.invoke('orbit:agent-clear'),
  agentTest: (key, baseUrl) => ipcRenderer.invoke('orbit:agent-test', key, baseUrl),
  loginItem: enable => ipcRenderer.invoke('orbit:login-item', enable),
  clipboardRead: () => ipcRenderer.invoke('orbit:clipboard-read'),
  clipboardWrite: text => ipcRenderer.invoke('orbit:clipboard-write', text),
  openFile: path => ipcRenderer.invoke('orbit:file-open', path),
  revealFile: path => ipcRenderer.invoke('orbit:file-reveal', path),
  copyPath: path => ipcRenderer.invoke('orbit:file-copy-path', path),
  copyText: text => ipcRenderer.invoke('orbit:copy-text', text),
  sendFiles: () => ipcRenderer.invoke('orbit:send-files'),
  openInbox: () => ipcRenderer.invoke('orbit:open-inbox'),
  sendPaths: paths => ipcRenderer.invoke('orbit:send-files', paths),
  retryTransfer: id => ipcRenderer.invoke('orbit:file-retry', id),
  pathForFile: file => webUtils.getPathForFile(file),
  dictationGet: () => ipcRenderer.invoke('orbit:dictation-get'),
  dictationSet: (enabled, accelerator) => ipcRenderer.invoke('orbit:dictation-set', enabled, accelerator),
  dictationTypeNow: () => ipcRenderer.invoke('orbit:dictation-type-now'),
  dictationSetModel: model => ipcRenderer.invoke('orbit:dictation-set-model', model),
  dictationFinish: buffer => ipcRenderer.invoke('orbit:dictation-finish', buffer),
  onDictationCapture: cb => { const f = (_e, action) => cb(action); ipcRenderer.on('orbit:dictation-capture', f); return () => ipcRenderer.removeListener('orbit:dictation-capture', f); },
  onDictationState: cb => { const f = (_e, s) => cb(s); ipcRenderer.on('orbit:dictation-state', f); return () => ipcRenderer.removeListener('orbit:dictation-state', f); },
  onDictationPreview: cb => { const f = (_e, payload) => cb(payload); ipcRenderer.on('orbit:dictation-preview', f); return () => ipcRenderer.removeListener('orbit:dictation-preview', f); },
});
